/** One choice: a Lucide icon or an emoji, as a space keeps it. */
export type IconChoice = {
  /** As a space keeps it: `lucide:<name>`, or the emoji. */
  value: string;
  label: string;
  /** What it is found by, lowercase. */
  words: string;
  glyph?: Icon;
  emoji?: string;
};

export type Category = { id: string; label: string; glyph: Icon; icons: IconChoice[]; emoji: IconChoice[] };

const icon = (name: string, glyph: Icon, words = ""): IconChoice => ({
  value: `lucide:${name}`,
  label: name.replaceAll("-", " ").replace(/ \d+$/, ""),
  words: `${name.replaceAll("-", " ")} ${words}`,
  glyph
});

const emoji = (char: string, words: string): IconChoice => ({
  value: char,
  label: words.split(" ")[0],
  words,
  emoji: char
});

