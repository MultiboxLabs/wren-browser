/** Every icon a space can have, by Lucide's name. */
export const SPACE_GLYPHS: Record<string, Icon> = Object.fromEntries(
  CATEGORIES.flatMap(({ icons }) => icons.map(({ value, glyph }) => [value.slice("lucide:".length), glyph!]))
);

export const ALL_CHOICES = CATEGORIES.flatMap(({ icons, emoji }) => [...icons, ...emoji]);

/** The choices `query` finds, by the start of any of their words. */
export function search(query: string, among = ALL_CHOICES): IconChoice[] {
  const terms = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return among;
  return among.filter(({ words }) => {
    const own = words.split(" ");
    return terms.every((term) => own.some((word) => word.startsWith(term)));
  });
}
